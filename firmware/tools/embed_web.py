# PlatformIO pre-build script: embeds ../web/*.html into include/web_assets.h so
# the board can serve the same pages over its own Wi-Fi (captive portal).
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO)
    root = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

web = os.path.join(root, "..", "web")
out = os.path.join(root, "include", "web_assets.h")
parts = ["// Generated by tools/embed_web.py from web/*.html. Do not edit.", "#pragma once"]
for name, var in [("index.html", "WEB_INDEX"), ("admin.html", "WEB_ADMIN")]:
    with open(os.path.join(web, name), encoding="utf-8") as f:
        html = f.read()
    assert ')BEARWEB"' not in html
    parts.append(f'static const char {var}[] = R"BEARWEB({html})BEARWEB";')
text = "\n".join(parts) + "\n"
if not os.path.exists(out) or open(out, encoding="utf-8").read() != text:
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
